export function t(value: string, locale: Locale) {
  if (locale === "en") {
    return value;
  }

  return translations[value] ?? value;
}

export function localize<T>(value: T, locale: Locale): T {
  if (locale === "en") {
    return value;
  }

  if (typeof value === "string") {
    return t(value, locale) as T;
  }

  if (Array.isArray(value)) {
    return value.map((item) => localize(item, locale)) as T;
  }

  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, localize(item, locale)])) as T;
  }

  return value;
}
